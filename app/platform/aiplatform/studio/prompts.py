"""Промпты шагов сценария. Первая строка — метка задачи: по ней фейковая LLM узнаёт, что ответить."""

from __future__ import annotations

TASK = "### task: "
POSTER, PLAN, SHORT = "poster", "plan", "short"
MAX_TEXT_CHARS = 60_000  # длиннее — обрезаем: модели хватит, а CLI не захлебнётся


def _clip(text: str) -> str:
    return text if len(text) <= MAX_TEXT_CHARS else text[:MAX_TEXT_CHARS] + "\n…"


def poster(text: str, title: str) -> str:
    return f"""{TASK}{POSTER}
Ты — арт-директор видео. Придумай обложку (первый кадр, превью) для ролика.
Название ролика: {title}

Напиши ОДИН промпт на английском для генератора картинок (FLUX / Z-Image):
что в кадре, композиция, свет, стиль, палитра. Кадр 16:9, яркий, читаемый в
маленьком размере, без текста и букв на картинке, без логотипов.
Ответь только промптом, одной строкой, без кавычек и пояснений.

Текст ролика:
{_clip(text)}
"""


def plan(paragraphs: list[str], title: str, max_slides: int) -> str:
    numbered = "\n\n".join(f"[{i}] {p}" for i, p in enumerate(paragraphs))
    return f"""{TASK}{PLAN}
Ты делаешь динамичную видео-презентацию под озвучку текста. Текст разбит на
абзацы с номерами [0], [1], … Озвучка идёт абзац за абзацем.

Сделай от 1 до {max_slides} слайдов. Слайд показывается с абзаца `para` и
держится до следующего слайда. Первый слайд — с абзаца 0. Номера по
возрастанию. На слайде: короткий заголовок (до 60 знаков) и 0–3 тезиса
(до 70 знаков каждый) — по-русски, своими словами, не цитатой. Для каждого
слайда — промпт картинки-фона на английском (image_prompt): сцена без текста
и букв, 16:9, в одном визуальном стиле со всеми слайдами. И промпт короткого
видео-фона на английском (video_prompt) для генератора видео (Veo, Kling,
LTX): та же сцена, одно непрерывное действие и движение камеры на 5 секунд,
без текста и склеек.

Ещё дай название ролика (title, до 90 знаков) и подпись к посту (post, до
800 знаков, по-русски: 2–4 строки о главном, можно **жирный**).

Ответь только JSON такого вида:
```json
{{"title": "…", "post": "…", "slides": [
  {{"para": 0, "title": "…", "bullets": ["…"], "image_prompt": "…", "video_prompt": "…"}}
]}}
```

Рабочее название: {title}

Абзацы:
{_clip(numbered)}
"""


def short(text: str, title: str, words: int) -> str:
    return f"""{TASK}{SHORT}
Сделай сценарий вертикального короткого видео (YouTube Shorts / TikTok /
Reels) по тексту ниже: 3–5 смысловых частей, всего не больше {words} слов —
это 45–60 секунд озвучки. Первая часть — цепляющий вопрос или факт, последняя —
вывод и призыв подписаться. У каждой части — заголовок для экрана (до 40
знаков) и текст для озвучки по-русски, разговорно, без списков, ссылок и кода.

Ответь только JSON такого вида:
```json
{{"beats": [{{"title": "…", "text": "…"}}]}}
```

Название: {title}

Текст:
{_clip(text)}
"""
