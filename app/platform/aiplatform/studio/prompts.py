"""Промпты шагов сценария. Первая строка — метка задачи: по ней фейковая LLM узнаёт, что ответить."""

from __future__ import annotations

from aiplatform.studio import slides

TASK = "### task: "
POSTER, PLAN, SHORT = "poster", "plan", "short"
MAX_TEXT_CHARS = 60_000  # длиннее — обрезаем: модели хватит, а CLI не захлебнётся


def _clip(text: str) -> str:
    return text if len(text) <= MAX_TEXT_CHARS else text[:MAX_TEXT_CHARS] + "\n…"


def poster(text: str, title: str) -> str:
    return f"""{TASK}{POSTER}
Ты — арт-директор видео. Придумай обложку (первый кадр, превью) для ролика.
Название ролика: {title}

Напиши ОДИН промпт на английском для генератора картинок (FLUX / Z-Image):
что в кадре, композиция, свет, стиль, палитра. Кадр 16:9, яркий, читаемый в
маленьком размере, без текста и букв на картинке, без логотипов.
Ответь только промптом, одной строкой, без кавычек и пояснений.

Текст ролика:
{_clip(text)}
"""


def digest_poster(text: str, day: str) -> str:
    """Обложка дайджеста, как image_prompt.md у narrator: что произошло — сценой и заголовками на картинке."""
    return f"""{TASK}{POSTER}
Ты — арт-директор новостного IT-канала. Придумай обложку дайджеста за {day}:
это первый кадр ролика, по нему зритель за секунду понимает, что произошло.

Напиши промпт на английском для генератора картинок. В нём:
- квадратный постер 1:1, обложка выпуска «срочные новости»;
- главный герой — классический гофер Go (голубой, круглые белые глаза,
  бежевая мордочка с двумя зубами) в динамичной сцене по мотивам
  главных событий дня: застывший момент действия, сильный контраст;
- текст на картинке по-русски — перечисли дословно, в кавычках:
  заголовок "Дайджест разработчика", дату (день и месяц словами) и 3–4
  заголовка событий, каждый до 30 знаков; заголовки — в плашках вокруг
  героя, у каждого маленькая иконка по теме;
- весь текст крупный и контрастный, читается на экране телефона;
- никаких других надписей, ссылок, логотипов, эмодзи и кода.
Ответь только промптом, без кавычек вокруг и пояснений.

Текст:
{_clip(text)}
"""


def numbered(paragraphs: list[str]) -> str:
    """Абзацы [N] с фразами (M) внутри — по ним LLM ставит слайду para и sent."""
    out = []
    for i, p in enumerate(paragraphs):
        out.append(f"[{i}] " + " ".join(f"({j}) {s}" for j, s in enumerate(slides.sentences(p))))
    return "\n\n".join(out)


def plan(paragraphs: list[str], title: str, target: int, aspect: str = "16:9") -> str:
    return f"""{TASK}{PLAN}
Ты делаешь динамичную видео-презентацию под озвучку текста. Текст разбит на
абзацы [0], [1], …, внутри абзаца фразы пронумерованы (0), (1), … Озвучка идёт
фраза за фразой.

Главное — ритм: каждые 3–5 секунд в кадре должно что-то меняться, иначе
зритель уходит. Поэтому слайдов много — примерно {target} (это не предел:
сколько нужно тексту, столько и делай, ограничения нет). Слайд показывается с
фразы `sent` абзаца `para` и держится до следующего слайда; одна фраза — это
3–8 секунд. Первый слайд — para 0, sent 0. Слайды по возрастанию (para, sent),
без повторов.

Слайды двух сортов — чередуй их, две картинки подряд — редко:
- `"kind": "image"` — сгенерированная картинка на весь кадр, сверху заголовок и
  0–3 тезиса. Промпт картинки на английском (image_prompt): сцена без текста и
  букв, кадр {aspect}, в одном визуальном стиле со всеми слайдами.
- динамические — их рисует сам рендер, элементы появляются по очереди:
  - `"kind": "bullets"` — заголовок и 2–5 пунктов (bullets);
  - `"kind": "stat"` — одно крупное число набегает от нуля: value (число),
    prefix/suffix (например "$", "%", " млн"), label — что это за число;
  - `"kind": "chart"` — график: chart "bar" (сравнение) или "line" (динамика
    во времени), unit, data — 2–8 точек {{"label": "…", "value": число}};
  - `"kind": "flow"` — схема из 2–5 шагов (steps, до 30 знаков каждый);
  - `"kind": "compare"` — сравнение: left и right {{"title": "…", "items": ["…"]}};
  - `"kind": "quote"` — цитата: text (до 200 знаков) и author.
  Числа, графики и цитаты — только из текста, ничего не выдумывай; нет данных —
  бери bullets, flow или compare.

Тексты на слайдах — по-русски, своими словами: заголовок до 60 знаков,
пункты до 70. Выбери до 3 самых динамичных моментов и только у этих
слайдов-картинок дай промпт короткого видео на английском (video_prompt) для
генератора видео (Veo, Kling, LTX): та же сцена, одно непрерывное действие и
движение камеры на 5 секунд, без текста и склеек. У остальных video_prompt —
пустая строка.

Ещё дай название ролика (title, до 90 знаков) и подпись к посту (post, до
800 знаков, по-русски: 2–4 строки о главном, можно **жирный**).

Ответь только JSON такого вида:
```json
{{"title": "…", "post": "…", "slides": [
  {{"para": 0, "sent": 0, "kind": "image", "title": "…", "bullets": ["…"], "image_prompt": "…", "video_prompt": ""}},
  {{"para": 0, "sent": 2, "kind": "stat", "title": "…", "value": 42, "suffix": "%", "label": "…"}},
  {{"para": 1, "sent": 0, "kind": "chart", "title": "…", "chart": "line", "unit": "млн",
    "data": [{{"label": "2023", "value": 1.5}}, {{"label": "2024", "value": 3.2}}]}},
  {{"para": 1, "sent": 1, "kind": "flow", "title": "…", "steps": ["…", "…", "…"]}}
]}}
```

Рабочее название: {title}

Абзацы:
{_clip(numbered(paragraphs))}
"""


def short(text: str, title: str, words: int) -> str:
    return f"""{TASK}{SHORT}
Сделай сценарий вертикального короткого видео (YouTube Shorts / TikTok /
Reels) по тексту ниже: 3–5 смысловых частей, всего не больше {words} слов —
это 45–60 секунд озвучки. Первая часть — цепляющий вопрос или факт, последняя —
вывод и призыв подписаться. У каждой части — заголовок для экрана (до 40
знаков) и текст для озвучки по-русски, разговорно, без списков, ссылок и кода.

Ответь только JSON такого вида:
```json
{{"beats": [{{"title": "…", "text": "…"}}]}}
```

Название: {title}

Текст:
{_clip(text)}
"""
